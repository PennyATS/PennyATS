import { randomUUID } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";

/**
 * Where uploaded files (resumes) live. Local disk for now; an S3-compatible
 * implementation can be added behind the same interface later.
 */
export interface FileStorage {
  put(bytes: Uint8Array, extension: string): Promise<string>;
  get(key: string): Promise<Uint8Array | null>;
  /** Remove a file. Missing files are ignored, so deletes can be retried safely. */
  delete(key: string): Promise<void>;
}

const KEY_PATTERN = /^[0-9a-f-]{36}\.[a-z]{2,5}$/;

class LocalDiskStorage implements FileStorage {
  constructor(private readonly dir: string) {}

  async put(bytes: Uint8Array, extension: string): Promise<string> {
    const key = `${randomUUID()}${extension.toLowerCase()}`;
    await mkdir(this.dir, { recursive: true });
    await writeFile(path.join(this.dir, key), bytes);
    return key;
  }

  async get(key: string): Promise<Uint8Array | null> {
    // Keys are generated by put(); reject anything else so a key can't escape the directory.
    if (!KEY_PATTERN.test(key)) return null;
    try {
      return await readFile(path.join(this.dir, key));
    } catch {
      return null;
    }
  }

  async delete(key: string): Promise<void> {
    if (!KEY_PATTERN.test(key)) return;
    await rm(path.join(this.dir, key), { force: true });
  }
}

/** STORAGE_DIR in .env, default `.data/uploads` next to the web app. Back this folder up. */
export const storage: FileStorage = new LocalDiskStorage(
  path.resolve(process.env.STORAGE_DIR ?? ".data/uploads"),
);

export function extensionOf(fileName: string): string {
  const ext = path.extname(fileName).toLowerCase();
  return /^\.[a-z]{2,5}$/.test(ext) ? ext : "";
}
