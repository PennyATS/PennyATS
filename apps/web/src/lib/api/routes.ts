/**
 * Every public API endpoint, declared once. Route handlers under app/api/v1 are built from
 * these entries (see handler.ts), and the OpenAPI document is generated from them (openapi.ts).
 * A unit test checks that each entry has a route file exporting its method, and the other way
 * round, so an endpoint can't exist without being documented.
 */
import type { z } from "zod";
import type { Permission, Scope } from "./scopes";
import * as s from "./schemas";

export type Method = "GET" | "POST" | "PATCH" | "DELETE";

export type ApiRoute = {
  operationId: string;
  method: Method;
  /** OpenAPI-style path below /api/v1, e.g. /jobs/{id}. */
  path: string;
  tag: string;
  summary: string;
  description?: string;
  /** Null only for /me, which any valid key may call. */
  scope: Scope | null;
  permission: Permission | null;
  params?: z.ZodObject;
  query?: z.ZodObject;
  body?: z.ZodType;
  response: z.ZodType;
  status?: 200 | 201;
  /** Writes are recorded in the audit log. */
  audit?: { resourceIdFrom?: "params" | "none" };
};

function route<const R extends ApiRoute>(r: R): R {
  return r;
}

